// sw.js — минимальный Service Worker.
//
// Добавлен 10.09.2026 РОВНО для одной цели: без зарегистрированного Service Worker Chrome не
// предлагает полноценную установку PWA (display:standalone, без адресной строки/меню Chrome) —
// вместо этого предлагает только "Установить и создать ярлык", который на деле просто открывает
// полноценный Chrome поверх сайта. Из-за этого весь интерфейс Chrome (включая функцию поиска по
// выделенному слову, которая ошибочно всплывала при наборе текста) оставался активным даже в
// "установленном" виде.
//
// Этот Service Worker НЕ кэширует данные (не хранит ответы, ничего не отдаёт из кэша) — хаб
// постоянно меняется (частые правки), и агрессивное кэширование страницы дало бы ту же самую
// проблему "показывает старую версию", которую мы только что чинили для ai-hub-shamil.ru, только
// теперь бы её создавал сам Service Worker, а не DNS. Обработчик fetch ниже нужен только для
// того, чтобы Chrome сам факт его наличия засчитал при проверке "можно ли установить как PWA" —
// сам он просто пропускает каждый запрос напрямую в сеть, ничего не подменяя и не кэшируя.
self.addEventListener("install", (event) => {
  self.skipWaiting();
});

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim());
});

// Chrome для критерия "можно ли установить как PWA" в ряде версий явно проверяет НАЛИЧИЕ
// обработчика fetch (это часть старого чек-листа установки) — раньше его не было вообще, из-за
// чего Chrome, судя по всему, и не предлагал полноценную установку, а только слабый вариант
// "Установить и создать ярлык". Добавлено 10.09.2026. Обработчик ничего не кэширует и не
// подменяет — просто пропускает каждый запрос напрямую в сеть, как будто его и нет.
self.addEventListener("fetch", (event) => {
  event.respondWith(fetch(event.request));
});
